#!/usr/bin/env bash
# streamdb performance benchmark harness (ROI P1 "Streamdb performance is a
# standing, self-perpetuating discipline"; `streamdb-perf-benchmark-recurring`).
#
# Runs the `streamdb_perf_bench` example (crates/pillar-streamdb/examples/
# streamdb_perf_bench.rs), which drives an identical op-path (seal+open) and
# view-fold (`OpLog::root`) workload through BOTH visibility profiles side by
# side:
#
#   * `public`    — unencrypted (public-visibility-class): the throughput/
#                   latency CEILING and fixed BASELINE.
#   * `encrypted` — cell-encrypted (AEAD-sealed): the guaranteed-
#                   confidentiality profile.
#
# and reports the public<->encrypted delta (the AEAD seal/unseal overhead,
# isolated from the signing+hashing cost both profiles pay) as a first-class
# metric alongside each profile's raw throughput.
#
# Tracked baseline: scripts/streamdb-perf-baseline.txt (plain `key=value`
# lines, committed alongside this script). First-ever run BOOTSTRAPS the
# baseline from the measured numbers and exits 0 (there is nothing yet to
# regress against). Every subsequent run compares the freshly measured
# ops/sec for each of the six throughput metrics against the tracked
# baseline: a drop beyond REGRESSION_TOLERANCE_PCT is a regression.
#
# Exit 0 = no metric regressed beyond tolerance (a clean run — the calling
#          honeybee self-defers +1 day per the task card).
# Exit 1 = at least one metric regressed beyond tolerance — the calling
#          honeybee reads $REPORT_FILE, files concrete tuning follow-up
#          task(s) per-metric, and only then may treat this run as handled.
#
# Usage: scripts/streamdb-perf-benchmark.sh [--ops N] [--fold-ops N] [--update-baseline]
#   --update-baseline   after a clean (or accepted-regression) run, rewrite
#                        the tracked baseline to the freshly measured numbers
#                        (e.g. after landing a tuning fix, or to accept an
#                        intentional new floor). Never implied automatically
#                        by a regression.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$here"

BASELINE_FILE="scripts/streamdb-perf-baseline.txt"
REPORT_FILE="$(mktemp "${TMPDIR:-/tmp}/streamdb-perf-report.XXXXXX")"
trap 'rm -f "$REPORT_FILE"' EXIT

# Metrics regression is judged on: throughput drop beyond this many percent
# vs. the tracked baseline. Generous enough to absorb ordinary shared-CI
# timing noise (this is wall-clock, not a dedicated bench rig) while still
# catching a real hot-path regression.
REGRESSION_TOLERANCE_PCT=25

OPS=4000
FOLD_OPS=4000
UPDATE_BASELINE=0
while [ $# -gt 0 ]; do
    case "$1" in
        --ops) OPS="$2"; shift 2 ;;
        --fold-ops) FOLD_OPS="$2"; shift 2 ;;
        --update-baseline) UPDATE_BASELINE=1; shift ;;
        *) echo "unknown arg: $1" >&2; exit 2 ;;
    esac
done

echo "streamdb-perf-benchmark: building release example..." >&2
cargo build --release -p pillar-streamdb --example streamdb_perf_bench >&2

echo "streamdb-perf-benchmark: running (ops=${OPS} fold-ops=${FOLD_OPS})..." >&2
./target/release/examples/streamdb_perf_bench --ops "$OPS" --fold-ops "$FOLD_OPS" >"$REPORT_FILE"

cat "$REPORT_FILE" >&2

get_metric() {
    # $1 = key, $2 = file
    awk -F= -v k="$1" '$1==k {print $2}' "$2"
}

METRICS="public_seal_ops_per_sec public_open_ops_per_sec public_fold_ops_per_sec encrypted_seal_ops_per_sec encrypted_open_ops_per_sec encrypted_fold_ops_per_sec"

if [ ! -f "$BASELINE_FILE" ]; then
    echo "streamdb-perf-benchmark: no tracked baseline yet — bootstrapping ${BASELINE_FILE} from this run." >&2
    {
        echo "# streamdb-perf-benchmark tracked baseline — ops/sec per metric."
        echo "# Regenerated by scripts/streamdb-perf-benchmark.sh --update-baseline;"
        echo "# do not hand-edit the numbers without re-running the harness."
        for m in $METRICS; do
            v=$(get_metric "$m" "$REPORT_FILE")
            echo "${m}=${v}"
        done
    } >"$BASELINE_FILE"
    echo "streamdb-perf-benchmark: baseline bootstrapped, exiting clean." >&2
    exit 0
fi

regressed=0
for m in $METRICS; do
    current=$(get_metric "$m" "$REPORT_FILE")
    baseline=$(get_metric "$m" "$BASELINE_FILE")
    if [ -z "$baseline" ]; then
        echo "streamdb-perf-benchmark: baseline missing metric '${m}' — treating as no prior floor." >&2
        continue
    fi
    # floor = baseline * (1 - tolerance/100); regression if current < floor.
    is_regression=$(awk -v cur="$current" -v base="$baseline" -v tol="$REGRESSION_TOLERANCE_PCT" \
        'BEGIN { floor = base * (1 - tol/100.0); print (cur < floor) ? 1 : 0 }')
    pct_change=$(awk -v cur="$current" -v base="$baseline" \
        'BEGIN { printf "%.2f", (cur - base) / base * 100.0 }')
    echo "streamdb-perf-benchmark: ${m} current=${current} baseline=${baseline} change=${pct_change}%" >&2
    if [ "$is_regression" = "1" ]; then
        echo "streamdb-perf-benchmark: REGRESSION on ${m} (current ${current} < floor of baseline ${baseline} minus ${REGRESSION_TOLERANCE_PCT}%)" >&2
        regressed=1
    fi
done

if [ "$UPDATE_BASELINE" = "1" ]; then
    echo "streamdb-perf-benchmark: --update-baseline set — rewriting ${BASELINE_FILE} to this run's numbers." >&2
    {
        echo "# streamdb-perf-benchmark tracked baseline — ops/sec per metric."
        echo "# Regenerated by scripts/streamdb-perf-benchmark.sh --update-baseline;"
        echo "# do not hand-edit the numbers without re-running the harness."
        for m in $METRICS; do
            v=$(get_metric "$m" "$REPORT_FILE")
            echo "${m}=${v}"
        done
    } >"$BASELINE_FILE"
fi

if [ "$regressed" = "1" ]; then
    echo "streamdb-perf-benchmark: FAIL — one or more metrics regressed beyond ${REGRESSION_TOLERANCE_PCT}% vs tracked baseline." >&2
    exit 1
fi

echo "streamdb-perf-benchmark: PASS — every metric within ${REGRESSION_TOLERANCE_PCT}% of tracked baseline." >&2
exit 0
